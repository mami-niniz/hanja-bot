def tg_api(method, params=None, get=False):
    """텔레그램 Bot API 호출. 실패해도 예외를 던지지 않고 dict 로 돌려줍니다."""
    if not TOKEN:
        raise SystemExit("오류: TELEGRAM_TOKEN 이 비어 있습니다. GitHub Secrets 를 확인하세요.")
    url = "https://api.telegram.org/bot%s/%s" % (TOKEN, method)
    if get:
        req = urllib.request.Request(url)
    else:
        data = urllib.parse.urlencode(params or {}).encode("utf-8")
        req = urllib.request.Request(url, data=data)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "replace")
        try:
            return json.loads(body)
        except ValueError:
            return {"ok": False, "error_code": e.code, "raw": body}


def build_card(c, n):
    return "\n".join([
        "[%d일차] 오늘의 한자" % n,
        "",
        "%s  (%s)" % (c["h"], c["e"]),
        "훈음 : %s" % c["m"],
        "",
        "▪ 예시 단어",
        "   %s (%s)" % (c["w1"], c["w1k"]),
        "   %s (%s)" % (c["w2"], c["w2k"]),
        "",
        "▪ 예문",
        "   %s" % c["s"],
        "   → %s" % c["t"],
    ])


def build_review(data, day):
    lines = ["지난 7일 한자 복습", ""]
    for i in range(6, -1, -1):
        if day - i < 0:
            continue
        c = data[(day - i) % len(data)]
        lines.append("· %s (%s) %s   - %s(%s)" % (c["h"], c["e"], c["m"], c["w1"], c["w1k"]))
    lines += ["", "오늘 하루도 화이팅입니다."]
    return "\n".join(lines)


