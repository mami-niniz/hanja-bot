def write_summary(md):
    """GitHub Actions 의 'Summary' 화면에 큰 글씨로 결과를 보여줍니다.
    (로그를 펼치지 않아도 바로 보입니다)"""
    path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not path:
        return
    try:
        with open(path, "a", encoding="utf-8") as fp:
            fp.write(md + "\n")
    except OSError:
        pass


def tg_api(method, params=None, get=False):
    """텔레그램 Bot API 호출. 실패해도 예외를 던지지 않고 dict 로 돌려줍니다."""
    if not TOKEN:
        raise SystemExit("오류: TELEGRAM_TOKEN 이 비어 있습니다. GitHub Secrets 를 확인하세요.")
    url = "https://api.telegram.org/bot%s/%s" % (TOKEN, method)
    if get:
        req = urllib.request.Request(url)
    else:
        data = urllib.parse.urlencode(params or {}).encode("utf-8")
        req = urllib.request.Request(url, data=data)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "replace")
        try:
            return json.loads(body)
        except ValueError:
            return {"ok": False, "error_code": e.code, "raw": body}


def esc(t):
    """텔레그램 HTML 서식에서 특수문자를 안전하게 처리합니다."""
    return (str(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def strip_tags(t):
    """미리보기용 - 서식 태그를 제거합니다."""
    return re.sub(r"<[^>]+>", "", t)


def hi(text, key):
    """문장 안의 오늘 한자를 굵게 표시합니다."""
    return text.replace(esc(key), "<b>%s</b>" % esc(key))


def build_card(c, n):
    """오늘의 한자 카드 (텔레그램 HTML 서식)"""
    h, e, m = esc(c["h"]), esc(c["e"]), esc(c["m"])
    line = "%s  (%s)   %s" % (h, e, m)
    label = "🎯 <b>오늘 배울 한자</b>\n"
    if HANJA_STYLE == "bold":
        head = "🎯 <b>%s  (%s)  %s</b>" % (h, e, m)
    elif HANJA_STYLE == "mark":
        head = "🎯 <b>오늘 배울 한자</b>\n<b><u>👉 %s  (%s)  %s 👈</u></b>" % (h, e, m)
    elif HANJA_STYLE == "box":
        head = label + "<pre><b>%s</b></pre>" % line
    else:  # 'quote' (기본)
        head = label + "<blockquote><b><u>%s</u></b></blockquote>" % line

    return "\n".join([
        "📖 <b>오늘의 한자</b>  ·  <b>%d일차</b>" % n,
        "━━━━━━━━━━━━━━━",
        "",
        head,
        "",
        "✏️ <b>예시 단어</b>",
        "　• <b>%s(%s)</b> · %s" % (esc(c["w1"]), read_word(c["w1"]), esc(c["w1k"])),
        "　• <b>%s(%s)</b> · %s" % (esc(c["w2"]), read_word(c["w2"]), esc(c["w2k"])),
        "",
        "📝 <b>예문</b>",
        "　%s" % annotate(c["s"], c["h"]),
        "　↳ %s" % esc(c["t"]),
    ])


def build_review(data, day):
    """일요일 - 지난 7일 복습 (텔레그램 HTML 서식)"""
    lines = ["🔄 <b>지난 7일 한자 복습</b>", "━━━━━━━━━━━━━━━", ""]
    for i in range(6, -1, -1):
        if day - i < 0:
            continue
        c = data[(day - i) % len(data)]
        lines.append("• <b>%s</b> <i>(%s)</i> %s" % (esc(c["h"]), esc(c["e"]), esc(c["m"])))
        lines.append("　　%s(%s) · %s" % (esc(c["w1"]), read_word(c["w1"]), esc(c["w1k"])))
    lines += ["", "💪 오늘 하루도 화이팅입니다!"]
    return "\n".join(lines)


