# 사전이 잘못 변환한 단어 수동 보정 (검수 후 추가)
WORD_EUM_FIX = {
    "不足": "부족", "容易": "용이", "樂器": "악기", "音樂": "음악",
}

HANJA_RUN = re.compile(r'[\u4e00-\u9fff]+')


def read_word(run):
    """한자 덩어리의 읽는 소리를 돌려줍니다."""
    if run in WORD_EUM_FIX:
        return WORD_EUM_FIX[run]
    if run in WORD_EUM:
        return WORD_EUM[run]
    return "".join(HANJA_EUM.get(ch, "") for ch in run)


def annotate(text, hi=None):
    """문장 안의 한자마다 (읽기)를 붙이고, 오늘 한자가 있으면 굵게 표시합니다."""
    t = esc(text)
    out, last = [], 0
    for m in HANJA_RUN.finditer(t):
        out.append(t[last:m.start()])
        run = m.group()
        seg = "%s(%s)" % (run, read_word(run))
        if hi and hi in run:
            seg = "<b>%s</b>" % seg
        out.append(seg)
        last = m.end()
    out.append(t[last:])
    return "".join(out)


